/**
 * Order submission for the buyer app (extracted from OrderReviewScreen so it can be tested; the database
 * client is INJECTED, nothing here talks to the network on its own). Pure JavaScript, explicit ".js" imports.
 *
 * Modes
 *   'create' / 'reorder'  a NEW order. Only ever INSERTs. Never updates or deletes any existing row, so the
 *                         order a repeat was based on can not be touched. Idempotent per clientReferenceId:
 *                         a retry (double tap, lost response, partial failure) resumes the order it already
 *                         created instead of creating a second one.
 *   'edit'                the existing buyer "Edit Order" behaviour, unchanged (update header, replace items,
 *                         audit log).
 *
 * Writes only what the app has always written: requirements {party_id, status, unit, notes:{address,
 * client_reference_id}} and requirement_items {product_name, category, quantity, unit, weight, gift, other_gift}.
 * The order id, order number (demand_ref) and timestamps are generated by the database.
 */
import { validateDraftItems, describeProblem, newClientReferenceId } from './repeatOrder.js';

export class SubmitError extends Error {
  constructor(code, message, extra = {}) {
    super(message);
    this.name = 'SubmitError';
    this.code = code;
    Object.assign(this, extra);
  }
}

/** Calls the wrapped function once at a time; concurrent calls receive the SAME in-flight result. */
export function singleFlight(fn) {
  let inFlight = null;
  return (...args) => {
    if (inFlight) return inFlight;
    inFlight = Promise.resolve().then(() => fn(...args)).finally(() => { inFlight = null; });
    return inFlight;
  };
}

/** The customer's current saved delivery address (profile), exactly as the app has always resolved it. */
export const currentSavedAddress = (session, customerProfile) =>
  session?.user?.user_metadata?.deliveryAddress?.address || customerProfile?.city || 'Saved Address';

export const resolveDeliveryAddress = ({ preferred, session, customerProfile }) =>
  (typeof preferred === 'string' && preferred.trim()) || currentSavedAddress(session, customerProfile);

export const PERMITTED_REQUIREMENT_STATUSES = new Set([
  'New',
  'Quotation Required',
  'Quotation Sent',
  'Negotiation',
  'Confirmed',
  'Lost',
  'Closed'
]);

/**
 * Normalizes any requirement status into one strictly permitted by req_status_check.
 * Guarantees that neither uppercase UI labels (e.g., 'NEW') nor invalid legacy defaults
 * (e.g., 'Open', 'Draft', 'Pending') can cause a 23514 check constraint violation.
 */
export function normalizeRequirementStatus(status) {
  if (!status || typeof status !== 'string') return 'New';
  const trimmed = status.trim();
  if (PERMITTED_REQUIREMENT_STATUSES.has(trimmed)) return trimmed;
  const upper = trimmed.toUpperCase();
  if (upper === 'NEW') return 'New';
  if (upper === 'CONFIRMED') return 'Confirmed';
  if (upper === 'CLOSED') return 'Closed';
  if (upper === 'QUOTATION REQUIRED') return 'Quotation Required';
  if (upper === 'QUOTATION SENT') return 'Quotation Sent';
  if (upper === 'NEGOTIATION') return 'Negotiation';
  if (upper === 'LOST') return 'Lost';
  return 'New';
}

export function buildRequirementPayload({ mode, customerProfile, existingOrder, address, clientReferenceId }) {
  const resolvedStatus = mode === 'edit' && existingOrder
    ? normalizeRequirementStatus(existingOrder.raw_status || existingOrder.status)
    : 'New';

  return {
    party_id: customerProfile.id,
    status: resolvedStatus,
    unit: 'Bags', // NOT NULL on requirements
    notes: JSON.stringify({ address, client_reference_id: clientReferenceId }),
  };
}

export const buildItemsPayload = (requirementId, items) => items.map((item) => ({
  requirement_id: requirementId,
  product_name: item.product_name,
  category: item.category || 'Uncategorized',
  quantity: item.quantity,
  unit: item.unit || 'Bags',
  weight: item.weight,
  gift: item.gift,
  other_gift: item.other_gift,
}));

const refFromNotes = (notes) => {
  if (!notes) return null;
  try {
    const parsed = typeof notes === 'string' ? JSON.parse(notes) : notes;
    return parsed && typeof parsed === 'object' ? parsed.client_reference_id || null : null;
  } catch (e) {
    return null;
  }
};

/**
 * The customer's own recent order that was created with this reference, if any. Read by party_id and matched
 * in code (no database operator on the notes column), so it works whatever the column type is.
 */
export async function findOrderByReference(client, partyId, clientReferenceId) {
  if (!clientReferenceId) return null;
  const { data, error } = await client
    .from('requirements')
    .select('id, demand_ref, status, notes, created_at, requirement_items(id)')
    .eq('party_id', partyId)
    .order('created_at', { ascending: false })
    .limit(10);
  if (error) throw new SubmitError('LOOKUP_FAILED', error.message || 'Could not check for an earlier attempt.');
  return (data || []).find((row) => refFromNotes(row.notes) === clientReferenceId) || null;
}

export const toOrderData = (requirement, mode) => ({
  id: requirement.id,
  order_no: requirement.demand_ref || 'PENDING',
  final_amount: 0,
  status: requirement.status || 'Order Lag Gaya',
  updated: mode === 'edit',
});

async function insertItems(client, requirementId, items) {
  const { error } = await client.from('requirement_items').insert(buildItemsPayload(requirementId, items));
  if (error) {
    throw new SubmitError('ITEMS_FAILED', error.message || 'Error inserting order items', { requirementId });
  }
}

async function submitEdit({ client, session, customerProfile, items, existingOrder, clientReferenceId, address }) {
  const payload = buildRequirementPayload({ mode: 'edit', customerProfile, existingOrder, address, clientReferenceId });
  const { data: updated, error: updateError } = await client.from('requirements').update(payload).eq('id', existingOrder.id).select().single();
  if (updateError) throw new SubmitError('UPDATE_FAILED', updateError.message || 'Error updating order');
  const { error: delError } = await client.from('requirement_items').delete().eq('requirement_id', existingOrder.id);
  if (delError) throw new SubmitError('UPDATE_FAILED', delError.message || 'Error updating order items');
  await client.from('activity_logs').insert({
    actor_id: session?.user?.id || null,
    module: 'Orders',
    action_type: 'UPDATED',
    entity_type: 'requirements',
    entity_id: existingOrder.id,
    summary: 'Buyer updated order items/details',
    metadata: { source: 'buyer_app', field: 'order_items', old_items_count: existingOrder.items?.length || 0, new_items_count: items.length },
  });
  if (!updated) throw new SubmitError('UPDATE_FAILED', 'Order placement did not return data');
  await insertItems(client, updated.id, items);
  return { requirement: updated, created: false, alreadyPlaced: false, orderData: toOrderData(updated, 'edit') };
}

/**
 * Places (or updates, in 'edit' mode) an order. Throws SubmitError with a customer-readable message.
 * Resolves with { requirement, created, alreadyPlaced, orderData, clientReferenceId }.
 */
export async function submitOrder({ client, session, customerProfile, items, mode = 'create', existingOrder = null, clientReferenceId, address, isHindi = false }) {
  if (!customerProfile?.id) throw new SubmitError('PROFILE_MISSING', 'Buyer profile not found.');
  if (!Array.isArray(items) || items.length === 0) throw new SubmitError('EMPTY', 'No items in order.');
  const problems = validateDraftItems(items);
  if (problems.length) {
    const first = problems[0];
    throw new SubmitError('INVALID_ITEMS', describeProblem(first.problems[0], first.product_name, isHindi), { problems });
  }

  if (mode === 'edit') {
    if (!existingOrder?.id) throw new SubmitError('EDIT_WITHOUT_ORDER', 'The order to edit was not found.');
    return { ...(await submitEdit({ client, session, customerProfile, items, existingOrder, clientReferenceId, address })), clientReferenceId };
  }

  const ref = clientReferenceId || newClientReferenceId();
  const prior = await findOrderByReference(client, customerProfile.id, ref);

  let requirement = prior;
  let created = false;
  if (!prior) {
    const { data, error } = await client
      .from('requirements')
      .insert(buildRequirementPayload({ mode, customerProfile, address, clientReferenceId: ref }))
      .select()
      .single();
    if (error) throw new SubmitError('HEADER_FAILED', error.message || 'Error inserting order');
    if (!data) throw new SubmitError('HEADER_FAILED', 'Order placement did not return data');
    requirement = data;
    created = true;
  }

  const alreadyHasItems = !!prior && (prior.requirement_items || []).length > 0;
  if (!alreadyHasItems) await insertItems(client, requirement.id, items); // resumes an attempt whose items were lost

  return {
    requirement,
    created,
    alreadyPlaced: alreadyHasItems,
    orderData: toOrderData(requirement, mode),
    clientReferenceId: ref,
  };
}
